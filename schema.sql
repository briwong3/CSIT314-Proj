-- Direct messages: customers can start a private conversation with a designer.
create table if not exists public.conversations(
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.profiles(id) on delete cascade,
  designer_id uuid not null references public.profiles(id) on delete cascade,
  project_id int references public.projects(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint conversations_distinct_participants check (customer_id <> designer_id)
);
create unique index if not exists conversations_unique_project
  on public.conversations(customer_id, designer_id, coalesce(project_id, 0));

create table if not exists public.messages(
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (length(trim(body)) > 0),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists messages_conversation_created
  on public.messages(conversation_id, created_at);

alter table public.conversations enable row level security;
alter table public.messages enable row level security;

drop policy if exists conversations_participant_read on public.conversations;
create policy conversations_participant_read on public.conversations
  for select to authenticated
  using (customer_id = auth.uid() or designer_id = auth.uid());

drop policy if exists conversations_customer_create on public.conversations;
create policy conversations_customer_create on public.conversations
  for insert to authenticated
  with check (
    customer_id = auth.uid()
    and exists (
      select 1 from public.profiles p
      where p.id = customer_id and p.role = 'customer' and p.status = 'active'
    )
    and exists (
      select 1 from public.profiles p
      where p.id = designer_id and p.role = 'designer' and p.status = 'active'
    )
  );

drop policy if exists messages_participant_read on public.messages;
create policy messages_participant_read on public.messages
  for select to authenticated
  using (exists (
    select 1 from public.conversations c
    where c.id = conversation_id and (c.customer_id = auth.uid() or c.designer_id = auth.uid())
  ));

drop policy if exists messages_participant_send on public.messages;
create policy messages_participant_send on public.messages
  for insert to authenticated
  with check (
    sender_id = auth.uid()
    and exists (
      select 1 from public.conversations c
      where c.id = conversation_id and (c.customer_id = auth.uid() or c.designer_id = auth.uid())
    )
  );

drop policy if exists profiles_conversation_participant_read on public.profiles;
create policy profiles_conversation_participant_read on public.profiles
  for select to authenticated
  using (exists (
    select 1 from public.conversations c
    where (c.customer_id = auth.uid() and c.designer_id = profiles.id)
       or (c.designer_id = auth.uid() and c.customer_id = profiles.id)
  ));

create or replace function public.mark_conversation_read(p_conversation_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.conversations c
    where c.id = p_conversation_id
      and (c.customer_id = auth.uid() or c.designer_id = auth.uid())
  ) then
    raise exception 'Conversation not found or access denied';
  end if;

  update public.messages
  set read_at = now()
  where conversation_id = p_conversation_id
    and sender_id <> auth.uid()
    and read_at is null;
end;
$$;

