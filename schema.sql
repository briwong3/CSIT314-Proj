create or replace function public.increment_views(pid integer)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  project_owner uuid;
  view_total integer;
begin
  update public.projects
  set views = coalesce(views, 0) + 1
  where id = pid
  returning designer_id, views into project_owner, view_total;

  if project_owner is null then
    raise exception 'Project not found';
  end if;

  insert into public.project_activity(project_id, designer_id, activity_type)
  values(pid, project_owner, 'view');

  if view_total >= 100 and view_total % 100 = 0 then
    insert into public.project_milestones(project_id, designer_id, view_count)
    values(pid, project_owner, view_total)
    on conflict (project_id, view_count) do nothing;
  end if;
end;
$$;
revoke all on function public.increment_views(integer) from public;
grant execute on function public.increment_views(integer) to authenticated;

