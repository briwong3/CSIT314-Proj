-- New sign-ups: only customer/designer allowed (admins are created by admins). Notify admin on designer sign-up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  r text := case when new.raw_user_meta_data->>'role'='designer' then 'designer' else 'customer' end;
  profile_name text := coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), 'User');
  company_name text := nullif(trim(new.raw_user_meta_data->>'company_name'), '');
begin
  insert into public.profiles(id,name,email,role)
  values(new.id, profile_name, new.email, r)
  on conflict (id) do update set name=excluded.name, email=excluded.email;

  if r='designer' and company_name is not null then
    begin
      insert into public.companies(designer_id,name)
      values(new.id, company_name);
    exception when others then
      raise warning 'Could not save company name for designer %: %', new.id, sqlerrm;
    end;
  end if;

  begin
    insert into public.audit_logs(actor,action,detail)
    values(new.id,'REGISTER',coalesce(new.email, 'Unknown email')||' as '||r);
  exception when others then
    raise warning 'Could not write registration audit log for user %: %', new.id, sqlerrm;
  end;

  if r='designer' then
    begin
      insert into public.notifications(message,kind)
      values('New interior designer registered: '||coalesce(new.email, 'Unknown email'),'designer_signup');
    exception when others then
      raise warning 'Could not create designer registration notification for user %: %', new.id, sqlerrm;
    end;
  end if;
  return new;
end;
$$;
drop trigger if exists on_signup on auth.users;
create trigger on_signup after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.sync_profile_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.email is distinct from old.email then
    update public.profiles set email = new.email where id = new.id;
  end if;
  return new;
end;
$$;
drop trigger if exists on_auth_email_update on auth.users;
create trigger on_auth_email_update after update of email on auth.users
  for each row execute function public.sync_profile_email();

create function log_profile_change() returns trigger language plpgsql security definer as $$
begin
  insert into audit_logs(actor,action,detail) values(auth.uid(),'UPDATE_USER',new.email||': role='||new.role||', status='||new.status||', name='||new.name);
  return new;
end $$;
create trigger on_profile_update after update on profiles for each row execute function log_profile_change();

