-- for project drafts
CREATE TABLE IF NOT EXISTS public.project_drafts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    project_id integer NOT NULL UNIQUE
        REFERENCES public.projects(id) ON DELETE CASCADE,

    designer_id uuid NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,

    title text NOT NULL,
    description text,
    category_id integer REFERENCES public.categories(id) ON DELETE SET NULL,
    budget numeric,
    completion_date date,
    stage text NOT NULL DEFAULT 'completed'
        CHECK (stage IN ('ongoing', 'completed')),
    visibility text NOT NULL DEFAULT 'draft'
        CHECK (visibility IN ('published', 'draft')),

    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.project_drafts ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE
ON public.project_drafts TO authenticated;

GRANT USAGE, SELECT
ON SEQUENCE public.project_drafts_id_seq TO authenticated;


CREATE POLICY project_drafts_designer_read
ON public.project_drafts
FOR SELECT TO authenticated
USING (designer_id = auth.uid());

CREATE POLICY project_drafts_designer_insert
ON public.project_drafts
FOR INSERT TO authenticated
WITH CHECK (
    designer_id = auth.uid()
    AND EXISTS (
        SELECT 1
        FROM public.projects
        WHERE projects.id = project_drafts.project_id
        AND projects.designer_id = auth.uid()
    )
);

CREATE POLICY project_drafts_designer_update
ON public.project_drafts
FOR UPDATE TO authenticated
USING (designer_id = auth.uid())
WITH CHECK (
    designer_id = auth.uid()
    AND EXISTS (
        SELECT 1
        FROM public.projects
        WHERE projects.id = project_drafts.project_id
        AND projects.designer_id = auth.uid()
    )
);
